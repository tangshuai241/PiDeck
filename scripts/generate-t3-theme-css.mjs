import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// T3's palette values stay verbatim in JSON. Only role names are adapted to
// PiDeck tokens; generated CSS and the theme balls share that single source.
const palettes = JSON.parse(readFileSync(new URL("../src/renderer/src/themes/t3-palettes.json", import.meta.url), "utf8"));
const roles = {
	"bg-app": "canvas",
	"bg-sidebar": "sidebar",
	"bg-panel": "surface",
	"bg-popover": "surfaceOverlay",
	"bg-input": "surface",
	"bg-muted": "muted",
	"bg-hover": "sidebarRowHover",
	"bg-active": "sidebarRowSelected",
	"text-primary": "text",
	"text-secondary": "textMuted",
	"text-tertiary": "secondaryLabel",
	"text-faint": "iconMuted",
	"text-inverse": "messageActionForeground",
	"border-subtle": "sidebarBorder",
	"border-default": "border",
	"border-strong": "input",
	accent: "messageAction",
	"accent-strong": "messageActionHover",
	"accent-soft": "accentSurface",
	"brand-green": "accent",
	"logo-green": "accent",
	"logo-green-mid": "messageAction",
	"logo-green-deep": "messageActionHover",
	"chat-card-bg": "surface",
	"chat-muted-bg": "codeBackground",
	"chat-control-bg": "secondary",
	"chat-table-bg": "surface",
	"chat-text-primary": "text",
	"chat-text-secondary": "textMuted",
	"chat-text-tertiary": "secondaryLabel",
	"chat-border": "border",
	"settings-canvas": "canvas",
	"settings-surface": "surfaceRaised",
	"settings-control": "secondary",
};
const css = ["/* Generated by scripts/generate-t3-theme-css.mjs. T3 Tools Inc., MIT; see ../themes/T3-LICENSE.txt. */"];
for (const theme of palettes) {
	for (const mode of ["light", "dark"]) {
		// Include data-theme in both selectors so generic accent rules cannot win.
		css.push(`:root[data-theme="${mode}"][data-appearance="${theme.id}"] {`);
		for (const [token, role] of Object.entries(roles)) css.push(`  --color-${token}: ${theme[mode][role]};`);
		css.push("}");
	}
}
const result = `${css.join("\n")}\n`;
const destination = new URL("../src/renderer/src/styles/t3-themes.css", import.meta.url);
if (process.argv.includes("--check")) {
	if (readFileSync(destination, "utf8") !== result) throw new Error("T3 theme CSS is stale. Run node scripts/generate-t3-theme-css.mjs.");
} else {
	writeFileSync(fileURLToPath(destination), result);
}
